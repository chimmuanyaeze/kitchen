"use client";

import { useEffect, useState, useRef } from "react";
import { useParams, useRouter } from "next/navigation";
import { supabase } from "@/lib/supabase";
import { ArrowLeft, ChevronRight, ChevronLeft, Mic,MicOff, Send, ChefHat, Volume2 } from "lucide-react";
import { RecipeDetail, RecipeStep, CookingSession } from "@/lib/types";
import { useHandsFreeVoice } from "@/hooks/useHandsFreeVoice";


export default function ActiveCookingPage() {
  const params = useParams();
  const router = useRouter();
  
  const [session, setSession] = useState<CookingSession | null>(null);
  const [recipe, setRecipe] = useState<RecipeDetail | null>(null);
  const [loading, setLoading] = useState(true);
  const [commandInput, setCommandInput] = useState("");
  const [isProcessingAI, setIsProcessingAI] = useState(false);
  const [showOriginal, setShowOriginal] = useState(false);
  const [showCompletionModal, setShowCompletionModal] = useState(false);
  const [dietaryPrefs, setDietaryPrefs] = useState<string | null>(null);

  //VOICE SELECTION STATE
  const [voiceGender, setVoiceGender] = useState<"female" | "male">("female");

  // Load saved voice preference from localStorage
  useEffect(() => {
    setTimeout(() =>{
      const savedGender = localStorage.getItem("kitchen_voice_gender") as "female" | "male";
      if (savedGender){
         setVoiceGender(savedGender);
      }
    },0);
    }, []);

  // Refs so the hook's onTranscript callback always calls the *current*
  // versions of these handlers, without needing them declared before the
  // hook call — they're assigned by the sync effect further down, right
  // after handleNextStep/handlePrevStep/processAICommand are defined.
  const handleNextStepRef = useRef<() => void>(() => {});
  const handlePrevStepRef = useRef<() => void>(() => {});
  const processAICommandRef = useRef<(text: string) => void>(() => {});

  // Hands-free listening (VAD + Whisper) and AI text-to-speech (Kokoro),
  // replacing the old browser SpeechRecognition/SpeechSynthesis APIs.
  const { isListening, isTranscribing, isSpeaking, lastHeard, toggleListening, speak } = useHandsFreeVoice({
    voiceGender,
    enabled: !!session,
    onTranscript: (transcript) => {
      if (["next", "next step", "continue", "move on", "step done", "advance"].some((cmd) => transcript.includes(cmd))) {
        handleNextStepRef.current();
      } else if (["previous", "previous step", "go back", "back", "last step"].some((cmd) => transcript.includes(cmd))) {
        handlePrevStepRef.current();
      } else if (["repeat", "read step", "what was that", "say that again"].some((cmd) => transcript.includes(cmd))) {
        if (session && recipe) {
          const currentStepText = recipe.recipe_steps.find((s) => s.step_number === session.current_step)?.instruction;
          const aiModified = session.modifications?.ai_steps?.[session.current_step];
          speak(`Step ${session.current_step}. ${aiModified || currentStepText}`, voiceGender);
        }
      } else if (transcript.length > 2) {
        processAICommandRef.current(transcript);
      }
    },
  });

  const handleVoiceGenderChange = (gender: "female" | "male") => {
    setVoiceGender(gender);
    localStorage.setItem("kitchen_voice_gender", gender);
    speak(gender === "female" ? "Female voice selected." : "Male voice selected.", gender);
  };

  // --- Step narration ---------------------------------------------------
  // Speak what is actually ON SCREEN. An AI-adapted version of a step is
  // generated by the auto-cleaner *after* you land on that step, so when
  // moving steps we can't always narrate immediately — otherwise we'd read
  // the original text and the adapted text would appear silently seconds
  // later. If a step still needs adapting, we park its number in
  // pendingNarrationRef and the auto-cleaner narrates it when it finishes.
  const pendingNarrationRef = useRef<number | null>(null);
  const currentStepRef = useRef<number | null>(null);
  const speakStepRef = useRef<(step: number, mods: CookingSession["modifications"]) => void>(() => {});

  const stepNeedsAdaptation = (mods: CookingSession["modifications"], step: number) =>
    !!mods?.scratchpad?.length && !mods?.ai_steps?.[step];

  const speakStep = (step: number, mods: CookingSession["modifications"]) => {
    if (!recipe) return;
    const original = recipe.recipe_steps.find((s) => s.step_number === step)?.instruction;
    const text = mods?.ai_steps?.[step] || original;
    if (text) speak(`Step ${step}. ${text}`, voiceGender);
  };

  // Fetch the session and its attached recipe
  useEffect(() => {
    async function fetchSession() {
      const { data: sessionData, error: sessionError } = await supabase
        .from("cooking_sessions")
        .select("*, recipes(*, recipe_steps(*))")
        .eq("id", params.sessionId)
        .single();

      if (sessionError || !sessionData) {
        console.error("Error fetching session:", sessionError);
        router.push("/");
        return;
      }

      // Sort the steps just like we did on the detail page
      if (sessionData.recipes && sessionData.recipes.recipe_steps) {
        sessionData.recipes.recipe_steps.sort((a: RecipeStep, b: RecipeStep) => a.step_number - b.step_number);
      }

      setSession(sessionData);
      setRecipe(sessionData.recipes);
      setLoading(false);
    }

    if (params.sessionId) {
      fetchSession();
    }
  }, [params.sessionId, router]);

  // Handle moving to the next step
  const handleNextStep = async () => {
    setShowOriginal(false); // Reset to showing AI version whenever we switch sessions
    if (!session || !recipe) return;

    // 1. Fetch the user's dietary profile from the secure vault
      const { data: profile } = await supabase
        .from("profiles")
        .select("dietary_preferences")
        .eq("id", session.user_id)
        .single();

      if (profile?.dietary_preferences) {
        setDietaryPrefs(profile.dietary_preferences);
      }
    
    const isLastStep = session.current_step === recipe.recipe_steps.length;
    
    if (isLastStep) {
      // Mark session as complete!
      await supabase.from("cooking_sessions").update({ status: "completed" }).eq("id", session.id);
      
      // Show the beautiful modal instead of the ugly alert
      setShowCompletionModal(true);
      speak("Meal completed! Bon appétit!", voiceGender);
    } else {
      // Move to the next step and save it to the database
      const nextStep = session.current_step + 1;
      await supabase.from("cooking_sessions").update({ current_step: nextStep }).eq("id", session.id);
      setSession({ ...session, current_step: nextStep });

      // Read the new step out loud — now, or once its AI adaptation is ready
      if (stepNeedsAdaptation(session.modifications, nextStep)) {
        pendingNarrationRef.current = nextStep;
      } else {
        pendingNarrationRef.current = null;
        speakStep(nextStep, session.modifications);
      }
    }
  };


  // Handle moving to the previous step
  const handlePrevStep = async () => {
    setShowOriginal(false); // Reset to showing AI version whenever we switch sessions
    if (!session || !recipe ||session.current_step === 1) return;

    const prevStep = session.current_step - 1;
    await supabase.from("cooking_sessions").update({ current_step: prevStep }).eq("id", session.id);
    setSession({ ...session, current_step: prevStep });

    // Read the previous step out loud — now, or once its AI adaptation is ready
    if (stepNeedsAdaptation(session.modifications, prevStep)) {
      pendingNarrationRef.current = prevStep;
    } else {
      pendingNarrationRef.current = null;
      speakStep(prevStep, session.modifications);
    }
  };

  // process Ai commands
  const processAICommand = async (commandText: string) => {
    if(!commandText.trim() || !recipe || !session) return;

    setIsProcessingAI(true);
    const currentStepText = recipe.recipe_steps.find((s) => s.step_number === session.current_step)?.instruction;

    try {
      const res = await fetch("/api/ai/command", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ 
          command: commandText, 
          currentStep: currentStepText,
          dietaryProfile: dietaryPrefs,
          scratchpad: session.modifications?.scratchpad || [] 
        }),
      });
      const aiResponse = await res.json();

      // check if the ai instructed a step nav action

      if(aiResponse.action === "next_step") {
        await handleNextStep();
      }

      // save modified steps for remebrance to the database
      if (aiResponse.updated_instruction) {
        const currentMods = { ...(session.modifications || {}) };
        const aiSteps = { ...(currentMods.ai_steps || {}) };
        const currentScratchpad = [...(currentMods.scratchpad || [])]; // Grab existing notes

        aiSteps[session.current_step] = aiResponse.updated_instruction;

        if (aiResponse.new_scratchpad_note) {
          currentScratchpad.push(aiResponse.new_scratchpad_note);
        }

        const newMods = { ...currentMods, ai_steps: aiSteps, scratchpad: currentScratchpad };
        
        await supabase
          .from("cooking_sessions")
          .update({ modifications: newMods })
          .eq("id", session.id);

        // Functional update: `session` here is from when the command started,
        // and the step may have changed while we waited on the AI.
        setSession((prev) => (prev ? { ...prev, modifications: newMods } : prev));
        setShowOriginal(false);

        // Say the adapted step itself, so hands-free matches the screen.
        speak(
          `${aiResponse.speech ? aiResponse.speech + " " : ""}${aiResponse.updated_instruction}`,
          voiceGender
        );
      } else if (aiResponse.speech && aiResponse.action !== "next_step") {
        // No rewrite — just the spoken reply (skipped for "next step", whose
        // own narration follows immediately).
        speak(aiResponse.speech, voiceGender);
      }
    } catch (error) {
      console.error("Failed to reach the Jarvis AI engine:", error);
      speak("We are having trouble connecting to network.", voiceGender);

    } finally {
      setIsProcessingAI(false);
      setCommandInput("");
    }
  };

  const handleAICommand = (e: React.FormEvent) => {
    e.preventDefault();
    processAICommand(commandInput);
  };

  // Keeps the refs the voice hook's onTranscript reads always pointing at
  // the latest versions of these handlers (the hook call sits above these
  // function declarations, so this sync avoids a circular declaration order).
  useEffect(() => {
    handleNextStepRef.current = handleNextStep;
    handlePrevStepRef.current = handlePrevStep;
    processAICommandRef.current = processAICommand;
    speakStepRef.current = speakStep;
  });

  useEffect(() => {
    currentStepRef.current = session?.current_step ?? null;
  }, [session]);

  // Wraps the hook's toggleListening so we still announce hands-free mode
  // turning on, same as the old implementation did.
  const handleToggleListening = () => {
    const turningOn = !isListening;
    toggleListening();
    if (turningOn) {
      speak("Hands free voice mode activated. Speak next, previous, or tell me missing ingredients.", voiceGender);
    }
  };

  
// --- THE AUTO-CLEANER ---
  // This watches the current step. If you click "Next", it automatically checks the scratchpad.
  useEffect(() => {
    // 1. EARLY EXITS: These completely prevent infinite loops!
    if (!session || !session.modifications?.scratchpad?.length) return;
    
    // If we already have an AI-modified version of this step, don't run it again.
    if (session.modifications?.ai_steps?.[session.current_step]) return;

    const autoCleanStep = async () => {
      setIsProcessingAI(true);
      const stepNum = session.current_step;
      let modsForNarration = session.modifications;
      const currentStepText = recipe?.recipe_steps.find((s) => s.step_number === session.current_step)?.instruction;

      try {
        // Silently send the step to the AI to be scrubbed
        const res = await fetch("/api/ai/command", {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({ 
            command: "Silently apply the scratchpad rules to this step.", 
            currentStep: currentStepText,
            dietaryProfile: dietaryPrefs,
            scratchpad: session.modifications?.scratchpad 
          }),
        });

        const aiResponse = await res.json();

        // If the AI rewrites it, save it immediately!
        if (aiResponse.updated_instruction) {
          const currentMods = { ...(session.modifications || {}) };
          const aiSteps = { ...(currentMods.ai_steps || {}) };
          aiSteps[session.current_step] = aiResponse.updated_instruction;
          
          const newMods = { ...currentMods, ai_steps: aiSteps };

          // Save to database
          await supabase.from("cooking_sessions").update({ modifications: newMods }).eq("id", session.id);
          
          // 2. THE FUNCTIONAL UPDATE: Fixes the React warning perfectly
          setSession(prev => prev ? { ...prev, modifications: newMods } : prev);
          setShowOriginal(false);
          modsForNarration = newMods;
        }
      } catch (error) {
        console.error("Background AI sync failed:", error);
      } finally {
        setIsProcessingAI(false);

        // If we arrived at this step by voice/buttons and were waiting on its
        // adaptation, narrate it now — the adapted text if we got one, the
        // original if not. Skip if the user has already moved on.
        if (pendingNarrationRef.current === stepNum) {
          pendingNarrationRef.current = null;
          if (currentStepRef.current === stepNum) {
            speakStepRef.current(stepNum, modsForNarration);
          }
        }
      }
    };

    autoCleanStep();
  }, [session, recipe, dietaryPrefs]); 


  if (loading || !recipe || !session) {
    return <div className="flex min-h-screen items-center justify-center bg-gray-50 dark:bg-gray-900 text-gray-600 dark:text-white transition-colors duration-200">Loading Kitchen...</div>;
  }

  // Find the exact instruction for the step the user is currently on
  const currentStepData = recipe.recipe_steps.find((s) => s.step_number === session.current_step);
// Check if the AI has modified this specific step in the database
  const aiModifiedInstruction = session?.modifications?.ai_steps?.[session.current_step];
  
  // Decide which text to show based on the toggle button
  const displayText = aiModifiedInstruction && !showOriginal 
    ? aiModifiedInstruction 
    : currentStepData?.instruction;

  return (
    <main className="flex flex-col min-h-screen bg-gray-50 dark:bg-gray-900 text-gray-900 dark:text-white transition-colors duration-200">
      {/* Top Header */}
      <div className="flex justify-between items-center p-6 border-b border-gray-200 dark:border-gray-800 transition-colors duration-200">
        <button
          type="button"
          title="Go back"
          aria-label="Go back"
          onClick={() => router.push("/")}
          className="p-2 bg-gray-200 dark:bg-gray-800 rounded-full hover:bg-gray-300 dark:hover:bg-gray-700 transition-colors"
        >
          <ArrowLeft className="w-5 h-5" />
        </button>
        <span className="text-sm font-medium text-gray-500 dark:text-gray-400">
          Step {session.current_step} of {recipe.recipe_steps.length}
        </span>
        <div className="w-9"></div> {/* Empty spacer for alignment */}

        {/* Male / Female Voice Selector Selector */}
        <div className="flex items-center gap-1.5 bg-gray-100 dark:bg-gray-800 p-1 rounded-xl border border-gray-200 dark:border-gray-700">
          <Volume2 className="w-4 h-4 ml-1 text-gray-500" />
          <button
            onClick={() => handleVoiceGenderChange("female")}
            className={`px-2.5 py-1 text-xs font-bold rounded-lg transition-all ${
              voiceGender === "female"
                ? "bg-blue-600 text-white shadow-sm"
                : "text-gray-600 dark:text-gray-400 hover:text-gray-900 dark:hover:text-white"
            }`}
          >
            👩 Female
          </button>
          <button
            onClick={() => handleVoiceGenderChange("male")}
            className={`px-2.5 py-1 text-xs font-bold rounded-lg transition-all ${
              voiceGender === "male"
                ? "bg-blue-600 text-white shadow-sm"
                : "text-gray-600 dark:text-gray-400 hover:text-gray-900 dark:hover:text-white"
            }`}
          >
            👨 Male
          </button>
        </div>
      </div>

      {/* Hands-Free Voice Status Banner */}
      {(isListening || isTranscribing || isSpeaking) && (
        <div className="bg-blue-600 text-white px-4 py-2 flex items-center justify-center gap-2 text-xs font-bold animate-pulse shadow-inner">
          <Mic className="w-4 h-4" />
          {isTranscribing ? (
            <span>Listening to what you said...</span>
          ) : isSpeaking ? (
            <span>Speaking...</span>
          ) : lastHeard ? (
            <span>Heard: &quot;{lastHeard}&quot;</span>
          ) : (
            <span>Hands-Free Listening Active — Say &quot;Next&quot;, &quot;Previous&quot;, or speak ingredients/changes out loud...</span>
          )}
        </div>
      )}

      {/* Main Instruction Area */}
      <div className="grow flex flex-col items-center justify-center p-8 text-center">
        <div className="flex flex-col items-center mb-8">
          <h2 className="text-3xl md:text-4xl font-bold leading-tight text-center">
            {displayText}
          </h2>
          
          {/* Only show the toggle button if the AI actually modified this step */}
          {aiModifiedInstruction && (
            <button
              onClick={() => setShowOriginal(!showOriginal)}
              className="mt-6 flex items-center gap-2 text-sm font-medium px-4 py-2 rounded-full transition-colors bg-blue-50 dark:bg-gray-800 text-blue-600 dark:text-blue-400 hover:bg-blue-100 dark:hover:bg-gray-700"
            >
              {showOriginal ? " 🤖 Switch to AI Adapted Version" : "🍲🥣 View Original Recipe Step"}
            </button>
          )}
        </div>
        
        {/* The AI Command Center */}
        <form 
          onSubmit={handleAICommand} 
          className="mt-8 w-full max-w-md flex items-center bg-white dark:bg-gray-800 rounded-full p-1 border border-gray-200 dark:border-gray-700 shadow-xl transition-colors duration-200"
        >
          {/* Hands-free Toggle Button */}
          <button
            type="button"
            onClick={handleToggleListening}
            disabled={isTranscribing || isSpeaking}
            className={`p-3 rounded-full transition-all disabled:opacity-60 ${
              isListening 
                ? "bg-red-500 text-white animate-bounce shadow-md" 
                : "text-blue-600 dark:text-blue-400 hover:bg-gray-100 dark:hover:bg-gray-700"
            }`}
            title={
              isTranscribing
                ? "Listening to what you said..."
                : isSpeaking
                ? "Speaking..."
                : isListening
                ? "Stop Hands-free Mode"
                : "Activate Hands-free Mode"
            }
          >
            {isTranscribing || isSpeaking ? (
              <span className="animate-pulse text-xs font-bold px-1">...</span>
            ) : isListening ? (
              <MicOff className="w-5 h-5" />
            ) : (
              <Mic className="w-5 h-5" />
            )}
          </button>

          <input
            type="text"
            value={commandInput}
            onChange={(e) => setCommandInput(e.target.value)}
            disabled={isProcessingAI}
            placeholder="Say 'Next' or type 'I don't have butter'..."
            className="grow bg-transparent text-gray-900 dark:text-white placeholder-gray-400 dark:placeholder-gray-500 focus:outline-none px-2 text-sm"
          />

          <button 
            type="submit"
            disabled={isProcessingAI || !commandInput.trim()}
            className="p-3 bg-blue-600 text-white rounded-full hover:bg-blue-500 disabled:opacity-50 disabled:bg-gray-400 dark:disabled:bg-gray-700 transition-colors"
          >
            {isProcessingAI ? (
              <span className="animate-pulse text-xs font-bold px-1">...</span>
            ) : (
              <Send className="w-4 h-4 ml-0.5" />
            )}
          </button>
        </form>
      </div>

      {/* Bottom Controls */}
      <div className="flex gap-4 p-6 bg-white dark:bg-gray-950 border-t border-gray-200 dark:border-transparent pb-safe transition-colors duration-200">
       <button 
          onClick={handlePrevStep}
          disabled={session.current_step === 1}
          className="w-1/3 bg-gray-100 dark:bg-gray-800 py-4 rounded-xl font-medium flex items-center justify-center gap-2 hover:bg-gray-200 dark:hover:bg-gray-700 text-gray-700 dark:text-white disabled:opacity-50 transition-colors"
        >
          <ChevronLeft className="w-5 h-5" />
          Previous
        </button>
        <button 
          onClick={handleNextStep}
          className="w-2/3 bg-gray-900 dark:bg-white text-white dark:text-gray-900 py-4 rounded-xl font-bold flex items-center justify-center gap-2 hover:bg-gray-800 dark:hover:bg-gray-100 transition-colors"
        >
          {session.current_step === recipe.recipe_steps.length ? "Finish Meal" : "Next Step"}
          {session.current_step !== recipe.recipe_steps.length && <ChevronRight className="w-5 h-5" />}
        </button>
      </div>
      
      {/* Completion Celebration Modal */}
      {showCompletionModal && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-gray-900/60 dark:bg-gray-950/80 backdrop-blur-md transition-opacity">
          <div className="bg-white dark:bg-gray-900 border border-gray-100 dark:border-gray-800 w-full max-w-sm rounded-3xl p-8 shadow-2xl text-center animate-in fade-in zoom-in duration-300">
            
            {/* Celebratory Icon */}
            <div className="w-24 h-24 bg-blue-50 dark:bg-blue-900/30 text-blue-600 dark:text-blue-500 rounded-full flex items-center justify-center mx-auto mb-6 shadow-inner shadow-blue-500/20">
              <ChefHat className="w-12 h-12" />
            </div>
            
            <h3 className="text-3xl font-bold text-gray-900 dark:text-white mb-3">Bon Appétit!</h3>
            
            <p className="text-gray-500 dark:text-gray-400 text-sm mb-8 leading-relaxed">
              You&apos;ve successfully conquered <span className="text-gray-900 dark:text-white font-medium">{recipe.title}</span>. Time to plate up and enjoy your masterpiece.
            </p>
            
            <button
              onClick={() => router.push("/")}
              className="w-full bg-blue-600 text-white py-4 rounded-xl font-bold flex items-center justify-center gap-2 hover:bg-blue-500 active:scale-95 transition-all shadow-lg shadow-blue-900/20 dark:shadow-blue-900/50"
            >
              Return to Dashboard
            </button>
          </div>
        </div>
      )}

    </main>
  );
}